import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import { afterEach, beforeEach, expect, it, vi } from "vitest"
const mocks = vi.hoisted(() => ({ user: vi.fn(), snapshot: vi.fn(), provider: vi.fn(), send: vi.fn() }))
vi.mock("@/lib/auth", () => ({ getCurrentUser: mocks.user }))
vi.mock("@/lib/case/service", () => ({ CaseError: class extends Error {} }))
vi.mock("@/lib/case/store", () => ({ readCase: vi.fn() }))
vi.mock("@/lib/i18n/server", async () => { const { makeT } = await import("@/lib/i18n/translate"); return { getT: async () => makeT("en") } })
vi.mock("@/lib/connectors/engine", () => ({ snapshotAllConnectors: mocks.snapshot }))
vi.mock("@/lib/teams-alert", () => ({ isTeamsAlertConfigured: () => false, sendTeamsAlert: mocks.send }))
vi.mock("@/lib/pmax/xray", () => ({ pmaxXray: mocks.provider }))
vi.mock("@/lib/pmax/controls", () => ({ readControlData: async () => ({}), proposeControls: vi.fn(), controlLexicon: vi.fn() }))
vi.mock("@/lib/search/xray", () => ({ searchXray: mocks.provider }))
vi.mock("@/lib/search/controls", () => ({ proposeSearch: vi.fn(), readSearchNegatives: vi.fn() }))
vi.mock("@/lib/meta/xray", () => ({ metaXray: mocks.provider }))
vi.mock("@/lib/overview/health", () => ({ healthOverview: async () => ({ fixes: [] }) }))
vi.mock("@/lib/case/board", () => ({ caseBoard: () => [] }))
vi.mock("@/lib/nba/store", () => ({ queryFor: () => [] }))
vi.mock("@/lib/search/split", () => ({ allSplits: () => [] }))
let dir: string
let route: typeof import("@/app/api/inbox/route")
let store: typeof import("@/lib/inbox/store")
beforeEach(async () => {
  vi.resetModules(); vi.clearAllMocks()
  dir = fs.mkdtempSync(path.join(os.tmpdir(), "inbox-quality-"))
  vi.spyOn(process, "cwd").mockReturnValue(dir)
  mocks.user.mockResolvedValue({ id: "fixture", role: "viewer", companies: ["MBC"] })
  mocks.snapshot.mockReturnValue({ google_ads: { id: "google_ads", status: "warning", configComplete: true, partialConfig: false, lastChecked: null, lastSuccess: null, failureReason: "PRIVATE MBI-account", maskedConfig: { account: "PRIVATE" } } })
  mocks.provider.mockRejectedValue(new Error("PRIVATE provider failure"))
  route = await import("@/app/api/inbox/route")
  store = await import("@/lib/inbox/store")
})
afterEach(() => { vi.restoreAllMocks(); fs.rmSync(dir, { recursive: true, force: true }) })
it.each([null, { id: "fixture", role: "viewer", companies: [] }])("denies before health or store source access: %j", async user => {
  mocks.user.mockResolvedValue(user)
  const read = vi.spyOn(fs, "readFileSync")
  expect((await route.GET()).status).toBe(user ? 403 : 401)
  expect(mocks.snapshot).not.toHaveBeenCalled()
  expect(read.mock.calls.some(([file]) => String(file).endsWith("inbox.json"))).toBe(false)
  expect(mocks.provider).not.toHaveBeenCalled()
})
it("actual persisted store -> GET scopes and normalizes errors; reads never call provider or send", async () => {
  const { fromGoogleHealth } = await import("@/lib/inbox/evidence")
  store.saveSnapshot({ builtAt: "2026-11-26T00:00:00.000Z", items: fromGoogleHealth(["MBC", "MBI"], null),
    errors: [{ company: "ALL", source: "search", error: "PRIVATE account-other" }, { company: "MBI", source: "meta", error: "PRIVATE" }],
    digest: { sentAt: "fixture", sent: false, keys: ["MBI:private"], error: "PRIVATE" } })
  const saved = fs.readFileSync(path.join(dir, "data/inbox.json"), "utf8")
  const first = await (await route.GET()).json()
  const second = await (await route.GET()).json()
  expect(first.items).toHaveLength(2)
  expect(first.items.every((i: { company: string }) => i.company === "MBC")).toBe(true)
  expect(first.items.map((i: { key: string }) => i.key)).toEqual(second.items.map((i: { key: string }) => i.key))
  expect(JSON.stringify(first)).not.toMatch(/PRIVATE|MBI|account-other/)
  expect(first.items.find((i: { source: string }) => i.source === "health").evidence.checkedAt).toBeNull()
  expect(fs.readFileSync(path.join(dir, "data/inbox.json"), "utf8")).toBe(saved)
  expect(mocks.provider).not.toHaveBeenCalled(); expect(mocks.send).not.toHaveBeenCalled()
})
it("existing build -> real store deduplicates repeated issues; health adds no live checks", async () => {
  const { buildInbox } = await import("@/lib/inbox/job")
  const first = await buildInbox(new Date("2026-11-26T10:00:00.000Z"))
  const second = await buildInbox(new Date("2026-11-26T10:01:00.000Z"))
  expect(new Set(first.items.map(i => i.key)).size).toBe(first.items.length)
  expect(first.items.map(i => i.key)).toEqual(second.items.map(i => i.key))
  expect(store.readSnapshot()?.items).toEqual(second.items)
  expect(first.items.filter(i => i.evidence?.sourceRef === "connector:google_ads")).toHaveLength(2)
  // Existing PMax/Search/Meta readers only: 3 per company per build.
  expect(mocks.provider).toHaveBeenCalledTimes(12)
  expect(mocks.snapshot).toHaveBeenCalledTimes(2)
  expect(mocks.send).not.toHaveBeenCalled()
})
it("GET handles an absent snapshot and reevaluates stored connection issues without rewriting", async () => {
  const empty = await (await route.GET()).json()
  expect(empty.builtAt).toBeNull()
  expect(empty.items[0].evidence.reasonCode).toBe("never_checked")
  const { fromGoogleHealth } = await import("@/lib/inbox/evidence")
  store.saveSnapshot({ builtAt: "2026-11-26T00:00:00.000Z", items: fromGoogleHealth(["MBC"], null), errors: [] })
  const checked = new Date().toISOString()
  mocks.snapshot.mockReturnValue({ google_ads: { id: "google_ads", status: "healthy", configComplete: true, lastChecked: checked, lastSuccess: checked } })
  expect((await (await route.GET()).json()).items).toEqual([])
  expect(store.readSnapshot()?.items).toHaveLength(1)
  mocks.snapshot.mockReturnValue({ google_ads: { id: "google_ads", status: "warning", configComplete: true, lastChecked: checked, lastSuccess: checked } })
  expect((await (await route.GET()).json()).items[0].evidence.reasonCode).toBe("recheck")
  expect(mocks.provider).not.toHaveBeenCalled(); expect(mocks.send).not.toHaveBeenCalled()
})
